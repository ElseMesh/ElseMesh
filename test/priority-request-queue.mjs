import assert from 'node:assert/strict';
import { PriorityRequestQueue } from '../src/network/PriorityRequestQueue.js';

const queue = new PriorityRequestQueue( 2 );
const started = [];
const releases = [];
const task = name => () => new Promise( resolve => { started.push( name ); releases.push( resolve ); } );
const first = queue.run( undefined, 1, task( 'first' ) );
const second = queue.run( undefined, 1, task( 'second' ) );
await new Promise( resolve => setImmediate( resolve ) );
assert.deepEqual( started, [ 'first', 'second' ] );
const texture = queue.run( undefined, 2, task( 'texture' ) );
const visual = queue.run( undefined, 1, task( 'visual' ) );
const collision = queue.run( undefined, 0, task( 'collision' ) );
const controller = new AbortController();
const aborted = queue.run( controller.signal, 0, task( 'aborted' ) );
controller.abort();
await assert.rejects( aborted, { name: 'AbortError' } );
releases.shift()();
await new Promise( resolve => setImmediate( resolve ) );
assert.deepEqual( started, [ 'first', 'second', 'collision' ] );
releases.shift()();
await new Promise( resolve => setImmediate( resolve ) );
assert.deepEqual( started, [ 'first', 'second', 'collision', 'visual' ] );
releases.shift()();
await new Promise( resolve => setImmediate( resolve ) );
assert.deepEqual( started, [ 'first', 'second', 'collision', 'visual', 'texture' ] );
for ( const release of releases ) release();
await Promise.all( [ first, second, collision, visual, texture ] );
console.log( 'PASS: shared request budget preserves priority and cancels queued work' );
