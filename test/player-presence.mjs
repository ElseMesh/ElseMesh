import assert from 'node:assert/strict';
import { DEFAULT_APPEARANCE, loadAppearance, saveAppearance } from '../src/player/AvatarAppearance.js';
import { PlayerPresence, PLAYER_PRESENCE_PROTOCOL, validatePresencePose } from '../src/network/PlayerPresence.js';

const own = 'player:' + 'a'.repeat(64), peer = 'player:' + 'b'.repeat(64);
const pose = (sequence, x = 0, yaw = 0) => ({ id: peer, protocol: PLAYER_PRESENCE_PROTOCOL, sequence, position: [x, 2, 3], yaw, pitch: 0, moving: true, mode: 'walk', avatarProfileId: 'elsemesh.avatar.stock-male/1', appearance: { ...DEFAULT_APPEARANCE }, updatedAt: 1000 + sequence });
const snapshot = (requestId, players, extra = {}) => ({ type: 'presence', worldId: 'elsemesh:test', requestId, playerId: own, players, ...extra });
const state = new PlayerPresence('elsemesh:test');
for ( const worldId of [ 'world:legacy', 'elsemesh-world:legacy', 'em-world:legacy' ] ) assert.throws( () => new PlayerPresence( worldId ), /Invalid presence configuration/, `presence rejects ${worldId}` );
assert.equal(state.observe(snapshot('1', [pose(1, 0, Math.PI - .1)]), { requestId: '1', now: 0 }), true);
state.observe(snapshot('2', [pose(2, 10, -Math.PI + .1)]), { requestId: '2', now: 100 });
const mid = state.interpolated(150)[0];
assert.equal(mid.position[0], 5);
assert.ok(Math.abs(mid.yaw - Math.PI) < 1e-10, 'Heading follows shortest route across wrap');
state.observe(snapshot('3', [pose(1, 99)]), { requestId: '3', now: 200 });
assert.equal(state.interpolated(250)[0].position[0], 10, 'Old sequence cannot replace pose');
assert.equal(state.interpolated(1600).length, 1, 'Silent peer remains visible until 120-second expiry');
assert.equal(state.interpolated(10099)[0].ghost, false, 'Remote avatar remains opaque before 10s');
assert.equal(state.interpolated(10100)[0].ghost, true, 'Remote avatar becomes a ghost at 10s');
assert.equal(state.interpolated(120100).length, 0, 'Remote avatar is removed at 120s without snapshots');
state.observe(snapshot('ghost-owner', [{...pose(2,10,-Math.PI+.1),ghost:true}]), {requestId:'ghost-owner', now:200});
assert.equal(state.interpolated(201)[0].ghost, true, 'Owner ghost flag applies without new movement sequence');
state.observe(snapshot('active-owner', [{...pose(2,10,-Math.PI+.1),ghost:false}]), {requestId:'active-owner', now:210});
assert.equal(state.interpolated(211)[0].ghost, false, 'Owner can revive ghost at identical movement sequence');
assert.throws(() => state.observe(snapshot('bad-ghost',[{...pose(3),ghost:'yes'}]), {requestId:'bad-ghost', now:220}), /Invalid presence player/);
assert.throws(() => state.observe(snapshot('4', [], { worldId: 'elsemesh:other' }), { requestId: '4' }));
assert.throws(() => state.observe(snapshot('4', [], { playerId: peer }), { requestId: '4' }));
assert.throws(() => state.observe(snapshot('4', []), { requestId: 'wrong' }));
assert.equal(state.players.size, 1, 'Rejected snapshot cannot remove peers');
state.observe(snapshot('4', []), { requestId: '4', now: 300 });
assert.equal(state.players.size, 0, 'Absent peers depart');
state.reset();
state.observe(snapshot('5', [pose(1)], { playerId: peer }), { requestId: '5', now: 400 });
assert.equal(state.players.size, 0, 'Own session is excluded');
for (const appearance of [{ ...DEFAULT_APPEARANCE, style: 'url' }, { ...DEFAULT_APPEARANCE, shirt: '#ABCDEF' }, { ...DEFAULT_APPEARANCE, model: '/evil.glb' }]) assert.throws(() => validatePresencePose({ ...pose(1), appearance }));
assert.throws(() => validatePresencePose({ ...pose(1), position: [Infinity, 0, 0] }));
assert.throws(() => validatePresencePose({ ...pose(1), pitch: 2 }));
assert.throws(() => validatePresencePose({ ...pose(1), mode: 'boat' }), /Invalid presence vehicle identity or speed/, 'vehicle presence requires type and speed in protocol v3');
assert.throws(() => validatePresencePose({ ...pose(1), protocol: 'elsemesh.player-presence/2' }), /Invalid presence sequence or protocol/, 'unsupported previous presence protocol versions are rejected');
assert.throws(() => validatePresencePose({ ...pose(1), avatarProfileId: 'elsemesh.avatar.stock-female/1' }), /Invalid presence avatar profile/, 'avatar profile ID must match its validated appearance style');
let key, value;
const storage = { setItem(k, v) { key = k; value = v; }, getItem() { return value; } };
assert.equal(saveAppearance(DEFAULT_APPEARANCE, storage), true);
assert.equal(key, 'elsemesh.avatar.v1');
assert.deepEqual(loadAppearance(storage), DEFAULT_APPEARANCE);
console.log('Player presence: validation, session isolation, departure, stale expiry and interpolation passed');
